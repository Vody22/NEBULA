'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const js=fs.readFileSync(path.join(root,'app.js'),'utf8');
const css=fs.readFileSync(path.join(root,'app.css'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
const unique=new Set(ids);
assert.equal(ids.length,unique.size,'No duplicate HTML IDs');
const refs=[...js.matchAll(/\$\(['"]#([A-Za-z0-9_-]+)['"]\)/g)].map(x=>x[1]);
for(const ref of refs)assert.ok(unique.has(ref),'Missing HTML element for JS selector: #'+ref);
const needed=['join','auth-form','nav','bottom-nav','discover-list','match-modal','match-go','match-close','report-modal','report-form','report-reason','report-details','network-status','onboarding-banner','onboarding-profile','invite-friends','hero-start','quick-profile','casting-live','casting-start','page-safety','page-profile'];
for(const n of needed)assert.ok(unique.has(n),'Missing V8 interface element '+n);
assert.ok(html.includes('role="dialog" aria-modal="true"'),'Match or report dialog must be accessible');
assert.ok(html.includes('storage')||html.includes('stockage temporaire'),'Temporary storage warning must remain visible');
assert.ok(html.includes('aucune équipe de modération humaine'),'Disclose missing moderation');
assert.ok(!html.includes('paiement obligatoire'),'No mandatory payment gate');
assert.ok(css.includes('CRUSHCAST V8'),'V8 visual theme should exist');
assert.ok(css.includes('@media(max-width:700px)'),'Mobile layout must exist');
assert.equal((css.match(/{/g)||[]).length,(css.match(/}/g)||[]).length,'CSS brace check');
assert.ok(sw.includes('crushcast-v8-static'),'PWA cache version must change');
assert.ok(sw.includes("if(!STATIC.includes(url.pathname))return"),'Avoid caching API responses and profiles');
console.log('CRUSHCAST V8 UI contract: OK ('+refs.length+' selectors, '+unique.size+' DOM IDs)');
